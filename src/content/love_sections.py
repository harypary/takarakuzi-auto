def day_details(data: dict) -> list:
    """1日ずつの詳しい解説（7日または14日）"""
    sign = data["sign"]
    lines = []
    for index, day in enumerate(data["days"]):
        ko = day["ko"]
        head = f"■ {md_wd(day['date'])}　{STARS[day['score']]}　{day['label']}"
        if ko["lucky_days"]:
            head += f"　【{'・'.join(ko['lucky_days'])}】"
        lines.append(head)
        lines.append(f"　暦：{ko['rokuyo']}／{ko['kyusei_name']}／月は{day['phase']}")
        lines.append(f"　{ROKUYO_TIME[ko['rokuyo']]}。")
        lines.append(f"　{SCORE_ADVICE[day['score']][sign['element']]}")
        if day["phase"] in MOON_ADVICE:
            lines.append(f"　{MOON_ADVICE[day['phase']]}")
        if ko["lucky_days"]:
            lines.append(f"　{'・'.join(ko['lucky_days'])}が重なります。気持ちを伝えるなら、この日を選ぶ価値があります。")
        lines.append(f"　この日にすると良いこと：{DO_BY_SCORE[day['score']][index % 3]}")
        lines.append(f"　避けたいこと：{AVOID_BY_SCORE[day['score']]}")
        lines.append("")
    return lines


