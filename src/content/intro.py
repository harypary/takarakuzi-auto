"""無料の紹介記事（このノートの読み方）の組み立て

集客の入口になる記事。数字は実データから差し込むので、内容が古くならない。
"""

from src.config import FEATURE_LABELS, FEATURES, GAMES, MODEL_NAME, SERIES
from src.content.article import SEP, _h
from src.content.compliance import DISCLAIMER

HASHTAGS = ["宝くじ", "宝くじ予想", "ナンバーズ予想", "ロト予想", "データ分析",
            "占い", "開運", "数字選択式宝くじ", "統計", "note"]

AXIS_NOTE = {
    "hot": "直近20回でよく出ている数字を評価します。勢いのある数字を逃さないための軸です。",
    "trend": "直近20回と直近100回を比べ、ここにきて出現ペースが上がってきた数字を拾います。",
    "cold": "長く出ていない数字を評価します。「そろそろ」という期待ではなく、間隔の偏りを数値として扱います。",
    "carry": "前回と同じ数字が続けて出る現象です。ロト6では全回平均で0.8個ほど起きています。",
    "slide": "前回の当せん数字の±1（隣の数字）が出る現象です。こちらも毎回一定の割合で起きています。",
    "koyomi": "抽せん日の九星・干支・数秘・五行から導いた「暦の数字」との重なりを評価します。",
}


def build_intro(totals: dict, weights: dict) -> tuple:
    title = f"【はじめに】暦×統計で数字を選ぶ ― このノートの読み方と、毎週の検証のしかた【{MODEL_NAME}】"

    P = [
        "はじめまして。このノートは、数字選択式宝くじ（ロト6・ロト7・ナンバーズ3・4）の数字選びを、"
        "「過去データの統計」と「暦（六曜・九星・干支・数秘）」という、性格のまったく違う二つの物差しで考える研究ノートです。",
        "",
        "最初にはっきりお伝えしておきたいことがあります。宝くじの抽せんは毎回リセットされる無作為のもので、"
        "どんな分析をしても当せん確率そのものが上がることはありません。それはこのノートも同じです。",
        "",
        "それでも、数字を選ぶ時間そのものは変えられます。なんとなく選んだ数字を待つ時間と、"
        "自分なりの根拠を持って選んだ数字を待つ時間は、まったく別のものです。"
        "このノートは、その「根拠」を毎回きちんと用意するための場所です。",
        "",
        _h("二つの物差しで数字を選ぶ"),
        "ひとつ目は統計です。" + "、".join(f"{GAMES[k].name}は全{v:,}回" for k, v in totals.items())
        + "の当せん番号を、出現頻度・未出現期間・合計値・奇数偶数・連番・よく一緒に出るペアといった角度から整理します。",
        "",
        "ふたつ目は暦です。抽せん日の六曜、日の九星、干支、五行の関係、日付の数秘から、その日に縁のある数字を導きます。"
        "昔から人が大切にしてきた「日を選ぶ」という考え方を、数字選びに重ねています。",
        "",
        "データだけでも、占いだけでもない。二つの物差しが同じ数字を指したとき、その数字を組み合わせの中心に置く――それがこのノートの考え方です。",
        "",
        _h("6つの分析軸"),
        "予想は次の6つの軸を点数化し、重みをつけて合計したスコアから組み立てます。",
        "",
    ]
    for f in FEATURES:
        P.append(f"■ {FEATURE_LABELS[f]}")
        P.append(f"　{AXIS_NOTE[f]}")
    P += [
        "",
        _h("毎週、正直に振り返ります"),
        "このノートがいちばん大切にしているのが「振り返り」です。",
        "",
        "毎週、先週の各抽せんについて、6つの軸それぞれが「偶然の期待値に比べてどれだけ当せん数字を捉えられたか」を数え、"
        "上振れした軸の比重を上げ、下振れした軸を下げます。当たった回だけを取り上げることはしません。外れた回も同じように載せます。",
        "",
        "そして、重みをどう動かしたのかを毎回の記事の無料部分に書いています。"
        "1週間の結果に振り回されないよう、一度に動かす幅には上限を設け、どの軸も5%〜40%の範囲に収まるようにしています。",
        "",
        "たとえば今週の重みはこうなっています。",
    ]
    for key, w in weights.items():
        line = "／".join(f"{FEATURE_LABELS[f].split('（')[0]} {w[f] * 100:.0f}%" for f in FEATURES)
        P.append(f"・{GAMES[key].name}：{line}")

    P += [
        "",
        _h("記事のラインナップ"),
    ]
    for key in ("numbers", "loto6", "loto7"):
        s = SERIES[key]
        when = {"numbers": "平日の抽せん日の前日", "loto6": "月曜・木曜の抽せんの前", "loto7": "金曜の抽せんの前"}[key]
        count = "各10パターン" if key == "numbers" else "10口"
        P.append(f"■ {s.title_name}予想（{s.price}円）")
        P.append(f"　{when}に投稿します。本命4・対抗3・穴3の{count}を、根拠つきで公開します。")
    P += [
        "",
        _h("記事の読み方"),
        "無料部分には、抽せん日の暦、先週の回顧（予想と結果の照合、軸ごとの成績）、今週の重みの変更、"
        "統計データの抜粋を載せています。ここだけでも、その回の傾向はつかめるようにしています。",
        "",
        "有料部分には、出現頻度やインターバルのランキングとその読み解き、出目の形の分析、よく一緒に出るペア、"
        "暦の詳しい解説、データ×暦の統合スコア、そして予想と1口ずつの性格を載せています。",
        "",
        _h("大切にしていること"),
        "・当たりを約束しません。抽せんが無作為であることを前提に書きます。",
        "・外れた回も隠しません。検証はすべて公開します。",
        "・購入は、生活に支障のない範囲で楽しむものだと考えています。",
        "",
        "数字を選ぶ時間が、少しでも楽しいものになりますように。次の抽せんでお会いしましょう。",
        "",
        DISCLAIMER,
    ]
    return title, "\n".join(P), list(HASHTAGS)
