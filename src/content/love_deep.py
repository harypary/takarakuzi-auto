def arc_section(data: dict) -> list:
    """期間を三幕で追う（具体的な場面）"""
    days = data["days"]
    third = max(len(days) // 3, 1)
    acts = [days[:third], days[third:third * 2], days[third * 2:]]
    labels = ["第一幕", "第二幕", "第三幕"]
    moods = [
        ("様子をうかがう時間", "まだ動かなくて大丈夫です。相手の連絡の間隔と、言葉の温度だけ覚えておいてください。"),
        ("距離が動く時間", "ここで一度、こちらから接点をつくります。重い相談ではなく、軽い用件がちょうどいい頃合いです。"),
        ("答えが見える時間", "相手の反応が、言葉ではなく行動に表れます。会う約束が出るか、話題が続くか。そこを見てください。"),
    ]
    lines = []
    for label, act, (mood, advice) in zip(labels, acts, moods):
        if not act:
            continue
        avg = sum(d["score"] for d in act) / len(act)
        head = f"■ {label}　{md_wd(act[0]['date'])}〜{md_wd(act[-1]['date'])}　{mood}"
        lines.append(head)
        lines.append(f"　平均 {avg:.1f}。" + ("追い風です。" if avg >= 3.6 else
                                             "向かい風です。" if avg <= 2.4 else "凪です。"))
        peak = max(act, key=lambda d: d["score"])
        lines.append(f"　この中では{md_wd(peak['date'])}（{peak['ko']['rokuyo']}・月は{peak['phase']}）が動きやすい日。")
        lines.append(f"　{advice}")
        lines.append("")
    return lines


